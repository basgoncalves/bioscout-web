/**
 * i18n.js -- interface language.
 *
 * Scope is everything the page shows: the interface, the warnings you are
 * meant to ACT on, and the long methodological notes. The notes were left in
 * English for a while on the argument that a mistranslated caveat does more
 * damage than an English one -- but a caveat nobody reads does no work at all,
 * and a page that switches to Portuguese and keeps its warnings in English
 * hides exactly the paragraphs saying which numbers to distrust. Wording drift
 * between the three is the real cost; `staleKeys()` and the test suite are
 * what keep it visible.
 *
 * Missing keys fall through to English rather than showing a key name, so a
 * half-finished translation degrades into a mixed page instead of gibberish.
 * `missingKeys()` lists what has not been translated, and the test suite fails
 * on a key that exists in a translation but no longer exists in English --
 * that is the one that rots silently.
 */
